def _eval_tree_py(node: dict, x_row: np.ndarray) -> float:
    while "leaf_value" not in node:
        f = int(node["split_feature"])
        thr = float(node["threshold"])
        node = node["left_child"] if float(x_row[f]) <= thr else node["right_child"]
    return float(node["leaf_value"])


def _compile_forest_to_pine_funcs(
    tag: str,
    booster_dump: dict,
    X_scaled: np.ndarray,
    max_trees: int,
    sc_mean: Sequence[float],
    sc_scale: Sequence[float],
    trees_per_fn: int = 5,
) -> Tuple[str, int, int, float]:
    """
    Pre-unscale StandardScaler thresholds into raw feature thresholds and compile
    the first `max_trees` LightGBM trees directly into unrolled Pine ternary helper
    functions (zero loops, zero array chunk loaders, ~10-20x faster in TradingView).
    """
    trees = booster_dump["tree_info"]
    per_tree = np.array([[_eval_tree_py(t["tree_structure"], row) for row in X_scaled] for t in trees])
    full_sum = per_tree.sum(axis=0)
    sub_sum = per_tree[:max_trees].sum(axis=0)
    corr = float(np.corrcoef(full_sum, sub_sum)[0, 1]) if np.std(full_sum) > 0 else 1.0

    used_trees = trees[:max_trees]
    node_count = 0

    def compile_expr(node: dict, used_feats: set) -> str:
        nonlocal node_count
        node_count += 1
        if "leaf_value" in node:
            return f"{float(node['leaf_value']):.8g}"
        f = int(node["split_feature"])
        used_feats.add(f)
        thr_raw = float(sc_mean[f]) + float(sc_scale[f]) * float(node["threshold"])
        left_s = compile_expr(node["left_child"], used_feats)
        right_s = compile_expr(node["right_child"], used_feats)
        return f"(x{f} <= {thr_raw:.9g} ? {left_s} : {right_s})"

    batch_funcs: List[str] = []
    batch_calls: List[str] = []
    for b_idx, start in enumerate(range(0, len(used_trees), trees_per_fn)):
        chunk = used_trees[start : start + trees_per_fn]
        used_feats: set = set()
        exprs = [compile_expr(t["tree_structure"], used_feats) for t in chunk]
        loads = [f"    float x{f} = array.get(x, {f})" for f in sorted(used_feats)]
        adds = [f"    acc += {e}" for e in exprs]
        fn_name = f"f_{tag}_{b_idx}"
        batch_calls.append(f"{fn_name}(x)")
        body = "\n".join(loads + ["    float acc = 0.0"] + adds + ["    acc"])
        batch_funcs.append(f"{fn_name}(array<float> x) =>\n{body}")

    sum_expr = " + ".join(batch_calls) if batch_calls else "0.0"
    batch_funcs.append(f"f_eval_{tag}(array<float> x) =>\n    {sum_expr}")
    return "\n\n".join(batch_funcs), min(max_trees, len(trees)), node_count, corr


def _emit_pine_func_loaders(
    specs: Sequence[Tuple[str, Sequence, bool, int]],
    calls_per_fn: int = 5,
) -> Tuple[str, str]:
    """
    Wrap chunked array loaders into small top-level helper functions (`f_ld_0`, `f_ld_1`, ...)
    called from a single tiny `if barstate.isfirst` block so `main()` bytecode stays tiny (avoids CE10295).
    """
    funcs: List[str] = []
    calls: List[str] = []
    fn_idx = 0

    for var_name, items, is_float, chunk_len in specs:
        fn_push = "f_push_floats" if is_float else "f_push_ints"
        arg_type = "array<float>" if is_float else "array<int>"
        str_items = [f"{x:.8g}" if is_float else str(int(x)) for x in items]
        chunks = [
            ",".join(str_items[i : i + chunk_len])
            for i in range(0, max(1, len(str_items)), chunk_len)
        ]
        for i in range(0, len(chunks), calls_per_fn):
            batch = chunks[i : i + calls_per_fn]
            fname = f"f_ld_{fn_idx}"
            fn_idx += 1
            body = "\n    ".join(f'{fn_push}(dst, "{c}")' for c in batch)
            funcs.append(f"{fname}({arg_type} dst) =>\n    {body}")
            calls.append(f"    {fname}({var_name})")

    init_block = "if barstate.isfirst\n" + "\n".join(calls)
    return "\n\n".join(funcs), init_block


